# frozen_string_literal: true

# Music `compose_detailed`, parsed: compose a song and get its metadata and audio file as separate
# fields instead of the raw `multipart/mixed` body.
#
# Requires the generated SDK to be loaded first (require 'elevenlabs'). It is not loaded by
# +require 'elevenlabs'+; require it explicitly:
#
#   require 'elevenlabs'
#   require 'elevenlabs/music/compose_detailed'
#
#   song = client.music.compose_detailed(prompt: 'Epic orchestral music', music_length_ms: 60_000)
#   puts song.json['song_metadata']['title']
#   File.binwrite(song.filename, song.audio)
#
# Once required, +client.music.compose_detailed+ returns an +Elevenlabs::Music::ComposeDetailedResponse+
# instead of the raw byte stream the generated method returns, matching +compose_detailed+ in the Python
# SDK and +composeDetailed+ in the TS SDK.
#
# Hand-written (see .fernignore). It prepends a module to the generated music client and runs the
# generated method unchanged, so no generated file changes and the request (base URL, credentials,
# retries, errors) is exactly the generated one.

require 'json'

module Elevenlabs
  module Music
    # A composed song: the metadata the API returns with it, the audio file, and its name.
    #
    # - +json+ [Hash] The JSON metadata part as the API sent it (string keys): +composition_plan+,
    #   +song_metadata+ (title, description, genres, languages, is_explicit), +words_timestamps+
    #   (nil unless +with_timestamps+ is set) and, with +with_waveform_visual+, +waveform_visual+.
    # - +audio+ [String] The audio file's bytes (ASCII-8BIT), in the requested +output_format+.
    # - +filename+ [String] The file name the API suggests for the audio, or +generated_music.mp3+.
    # - +song_id+ [String, nil] The +song-id+ response header, sent when +store_for_inpainting+ is set.
    ComposeDetailedResponse = Data.define(:json, :audio, :filename, :song_id)

    module ComposeDetailed
      DEFAULT_FILENAME = 'generated_music.mp3'

      # The generated method, captured before this module is prepended, so the override can run it
      # on a recording client without calling itself.
      GENERATED = ::Elevenlabs::Music::Client.instance_method(:compose_detailed)
      private_constant :GENERATED

      # Compose a song from a prompt or a composition plan, and return its metadata and audio.
      #
      # Takes the same parameters as the generated +compose_detailed+.
      #
      # @return [ComposeDetailedResponse]
      # @raise [::Elevenlabs::Errors::ResponseError] The API returned an error status.
      # @raise [::Elevenlabs::Errors::ApiError] The response isn't a multipart body with a JSON part and
      #   an audio part.
      def compose_detailed(request_options: {}, **params)
        recorder = StreamRecorder.new(@client)
        stream = GENERATED.bind_call(self.class.new(client: recorder), request_options: request_options, **params)
        parsed = MultipartParser.parse(stream.read)
        ComposeDetailedResponse.new(
          json: parsed[:json],
          audio: parsed[:audio],
          filename: parsed[:filename],
          song_id: recorder.last_response&.[]('song-id'),
        )
      end

      # Stands in for the raw HTTP client and remembers the response it streamed, so the +song-id+
      # header can be read after the body. The generated byte-stream decoder returns only the body.
      #
      # @api private
      class StreamRecorder
        attr_reader :last_response

        def initialize(raw_client)
          @raw_client = raw_client
          @last_response = nil
        end

        # Named like the raw client's method, which the generated byte-stream decoder calls.
        def stream(request, &block)
          @raw_client.stream(request) do |response|
            @last_response = response
            yield(response)
          end
        end

        # Anything else the generated code asks of the raw client goes straight through.
        def method_missing(name, *args, **kwargs, &block)
          return super unless @raw_client.respond_to?(name)

          @raw_client.public_send(name, *args, **kwargs, &block)
        end

        def respond_to_missing?(name, include_private = false)
          @raw_client.respond_to?(name, include_private) || super
        end
      end

      # Splits the +multipart/mixed+ body of +POST /v1/music/detailed+ into its JSON part and its audio
      # part. Works on bytes throughout, so the audio is returned exactly as sent: the line break before
      # each delimiter and the closing +--boundary--+ are stripped, never left on the end of the audio.
      #
      # @api private
      module MultipartParser
        module_function

        # @param body [String]
        # @return [Hash] +{ json:, audio:, filename: }+
        # @raise [::Elevenlabs::Errors::ApiError]
        def parse(body)
          body = body.b
          first_break = body.index("\n")
          delimiter = (first_break.nil? ? body : body.byteslice(0, first_break)).strip
          raise ::Elevenlabs::Errors::ApiError, 'Could not find the multipart boundary in the music response' unless delimiter.start_with?('--') && delimiter.bytesize > 2

          # The body uses one line ending throughout; read it from the delimiter line.
          line_break = !first_break.nil? && first_break.positive? && body.getbyte(first_break - 1) == 13 ? "\r\n" : "\n"

          parts = []
          pos = body.index(delimiter)
          until pos.nil?
            after = pos + delimiter.bytesize
            break if body.byteslice(after, 2) == '--' # Closing delimiter.

            start = body.byteslice(after, line_break.bytesize) == line_break ? after + line_break.bytesize : after
            nxt = body.index(line_break + delimiter, start)
            finish = nxt.nil? ? body.bytesize : nxt
            parts << split_part(body.byteslice(start, finish - start), line_break)
            pos = nxt.nil? ? nil : nxt + line_break.bytesize
          end

          json_part = nil
          audio_part = nil
          parts.each do |part|
            is_json = part[:headers].fetch('content-type', '').downcase.start_with?('application/json')
            if json_part.nil? && is_json
              json_part = part
            elsif audio_part.nil? && !is_json
              audio_part = part
            end
          end

          raise ::Elevenlabs::Errors::ApiError, 'Could not find the JSON part in the music response' if json_part.nil?

          metadata = begin
            ::JSON.parse(json_part[:body].dup.force_encoding(::Encoding::UTF_8).strip)
          rescue ::JSON::ParserError => e
            raise ::Elevenlabs::Errors::ApiError, "Could not parse the JSON part of the music response: #{e.message}"
          end
          raise ::Elevenlabs::Errors::ApiError, 'The JSON part of the music response is not an object' unless metadata.is_a?(::Hash)

          raise ::Elevenlabs::Errors::ApiError, 'Could not find the audio part in the music response' if audio_part.nil? || !audio_part[:separated]

          { json: metadata, audio: audio_part[:body], filename: filename(audio_part[:headers]['content-disposition']) }
        end

        def split_part(part, line_break)
          # Prepend a line break so a part with no headers (the blank line straight after the delimiter)
          # is found at offset 0 too.
          with_break = line_break + part
          separator = with_break.index(line_break * 2)
          return { headers: headers(part, line_break), body: ''.b, separated: false } if separator.nil?

          header_block = with_break.byteslice(line_break.bytesize, [separator - line_break.bytesize, 0].max)
          body = with_break.byteslice(separator + (2 * line_break.bytesize), with_break.bytesize)
          { headers: headers(header_block, line_break), body: body, separated: true }
        end

        def headers(block, line_break)
          block.split(line_break).each_with_object({}) do |line, acc|
            name, value = line.split(':', 2)
            acc[name.strip.downcase] = value.strip unless value.nil?
          end
        end

        def filename(disposition)
          match = disposition&.match(/filename="([^"]+)"|filename=([^;\s]+)/i)
          name = match && (match[1] || match[2])
          name.nil? || name.empty? ? DEFAULT_FILENAME : name.dup.force_encoding(::Encoding::UTF_8)
        end
      end
    end

    Client.prepend(ComposeDetailed)
  end
end
