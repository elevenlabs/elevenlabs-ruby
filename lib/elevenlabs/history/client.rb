        @client = client
      end

      # Returns a list of your generated audio (e.g. text to speech, speech to speech, Studio, dubbing). Music and SFX generations are not included and cannot currently be retrieved via the API.
      def list(request_options: {}, **params)
        params = ::Elevenlabs::Internal::Types::Utils.normalize_keys(params)
        query_params = {}
        query_params['page_size'] = params[:page_size] if params.key?(:page_size)
        query_params['start_after_history_item_id'] = params[:start_after_history_item_id] if params.key?(:start_after_history_item_id)
        query_params['voice_id'] = params[:voice_id] if params.key?(:voice_id)
        query_params['model_id'] = params[:model_id] if params.key?(:model_id)
        query_params['date_before_unix'] = params[:date_before_unix] if params.key?(:date_before_unix)
        query_params['date_after_unix'] = params[:date_after_unix] if params.key?(:date_after_unix)
        query_params['sort_direction'] = params[:sort_direction] if params.key?(:sort_direction)
        query_params['search'] = params[:search] if params.key?(:search)
        query_params['source'] = params[:source] if params.key?(:source)
        request = ::Elevenlabs::Internal::JSON::Request.new(
          base_url: request_options[:base_url],
          method: 'GET',
          path: 'v1/history',
          query: query_params,
          request_options: request_options,
        )
        response = @client.send(request)
        code = response.code.to_i
        if code.between?(200, 299)
          result = ::Elevenlabs::Internal::Http::ResponseBody.decode(response) { |body| ::Elevenlabs::Types::GetSpeechHistoryResponse.load(body) }
          result.validate! if result.respond_to?(:validate!)
          result
        else
          error_class = ::Elevenlabs::Errors::ResponseError.subclass_for_code(code)
          error_body = ::Elevenlabs::Errors::ResponseError.load_body(response.body, { 422 => ::Elevenlabs::Types::HTTPValidationError }[code])
          raise error_class.new(response.body, code: code, body: error_body, headers: response.to_hash)
        end
      end

